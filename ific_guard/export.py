"""Reproducible, issue-specific evaluation files; never export mutable cross-issue cases."""
import csv
import hashlib
import json
import subprocess
from dataclasses import asdict
from datetime import UTC, datetime
from pathlib import Path
from time import perf_counter

from sqlalchemy import select

from .config import get_settings
from .db import session_scope
from .models import Artifact
from .screening.rules import space_rules
from .screening.space import IN_SCOPE_REASONS, MdbReader, SpaceIssue

FIELDS = (
    "rank", "domain", "issue_no", "rule_id", "family_id", "severity", "title",
    "adm", "network", "notice_ids", "comment_deadline", "source_url", "source_sha256",
)


def _file_hash(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def _code_version() -> dict:
    try:
        def git(*args):
            return subprocess.check_output(
                ["git", *args], cwd=Path(__file__).resolve().parents[1], text=True,
                stderr=subprocess.DEVNULL,
            ).strip()
        return {"commit": git("rev-parse", "HEAD"), "dirty": bool(git("status", "--porcelain"))}
    except (OSError, subprocess.CalledProcessError):
        return {"commit": None, "dirty": None}


def export_issue(domain: str, issue_no: int, out: Path, *, sha256: str | None = None) -> dict:
    """Evaluate the latest imported revision (or an explicit hash) without changing reviews.

    Re-evaluation is intentional: Case is a mutable cross-issue review record, not
    a historical snapshot. No mail or events are generated by this operation.
    """
    if domain != "space":
        raise ValueError("Terrestrial export requires the land-mobile rules (tickets 08-10).")
    settings = get_settings()
    with session_scope() as session:
        query = select(Artifact).where(Artifact.domain == domain, Artifact.issue_no == issue_no)
        if sha256:
            query = query.where(Artifact.sha256 == sha256)
        artifact = session.scalars(query.order_by(Artifact.id.desc())).first()
        if artifact is None:
            raise ValueError(f"No imported {domain} issue {issue_no} matching the requested revision.")

    started = perf_counter()
    reader = MdbReader(artifact.mdb_path)
    issue = SpaceIssue(reader)
    rules = space_rules(settings)
    hits = [hit for rule in rules for hit in rule.run(issue)]
    hits.sort(key=lambda h: (
        {"high": 0, "medium": 1, "low": 2}[h.severity],
        h.comment_deadline.isoformat() if h.comment_deadline else "9999-12-31",
        h.rule_id, h.family_id,
    ))
    records = []
    for rank, hit in enumerate(hits, 1):
        record = asdict(hit)
        record.update(rank=rank, domain=domain, issue_no=issue_no,
                      source_url=artifact.source_url, source_sha256=artifact.sha256)
        record["notice_ids"] = [str(n) for n in sorted(hit.notice_ids)]
        record["comment_deadline"] = hit.comment_deadline.isoformat() if hit.comment_deadline else None
        record["details"].setdefault("method", "screening")
        record["details"]["source"] = {
            "domain": domain, "issue_no": issue_no,
            "notice_ids": record["notice_ids"], "sha256": artifact.sha256,
        }
        records.append(record)

    # Explicit whitelist: credentials and mail recipients never belong in exports.
    config = {name: getattr(settings, name) for name in (
        "gso_visible_west_deg", "gso_visible_east_deg", "ngso_min_inclination_deg", "comment_window_months",
    )}
    config["m4_filter_sha256"] = _file_hash(settings.m4_filter_path)
    manifest = {
        "format_version": 1, "provisional_format": True,
        "domain": domain, "issue_no": issue_no, "source_url": artifact.source_url,
        "source_sha256": artifact.sha256,
        "mdb_sha256": _file_hash(Path(artifact.mdb_path)),
        "source_size_bytes": artifact.size_bytes, "code_version": _code_version(),
        "code_sha256": {
            str(path.relative_to(Path(__file__).parent)).replace("\\", "/"): _file_hash(path)
            for path in sorted(Path(__file__).parent.rglob("*.py"))
        },
        "config": config, "rule_ids": [rule.id for rule in rules], "case_count": len(records),
        "scope": {"notice_reasons": sorted(IN_SCOPE_REASONS), "ap30_coverage": "not implemented"},
        "limitations": [
            "Possible concerns for expert review, not confirmed interference or regulatory breaches.",
            "AP30/AP30A/AP30B are not screened; current scope is API/A and CR/C.",
            "No beam coverage or power-flux-density calculation.",
            "The current M4 file merges 3400-4200 MHz and can miss 3400-3800 MHz concerns.",
            "Special-interest station overlap is not yet implemented.",
            "Comment deadlines are estimates requiring expert confirmation.",
        ],
        "generated_at": datetime.now(UTC).isoformat(),
        "run_time_s": round(perf_counter() - started, 6),
    }
    out.mkdir(parents=True, exist_ok=True)
    (out / "cases.json").write_text(json.dumps(records, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
    with (out / "cases.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=FIELDS, extrasaction="ignore")
        writer.writeheader()
        for record in records:
            writer.writerow({**record, "notice_ids": ";".join(record["notice_ids"])})
    manifest["output_sha256"] = {
        name: hashlib.sha256((out / name).read_bytes()).hexdigest()
        for name in ("cases.csv", "cases.json")
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest
